class ClientStorage {
  private data: ClientDatabaseSchema;

  constructor() {
    this.data = this.load();
  }

  private load(): ClientDatabaseSchema {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (parsed.users && parsed.services && parsed.bookings) {
          return parsed;
        }
      }
    } catch {
      // fallback
    }
    const initial = getInitialData();
    this.save(initial);
    return initial;
  }

  public save(data: ClientDatabaseSchema): void {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
      this.data = data;
    } catch {
      // ignore
    }
  }

  public get(): ClientDatabaseSchema {
    return this.data;
  }

  public update(updater: (db: ClientDatabaseSchema) => void): ClientDatabaseSchema {
    updater(this.data);
    this.save(this.data);
    return this.data;
  }
}

export const clientDb = new ClientStorage();
